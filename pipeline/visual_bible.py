"""Visual Bible — LLM-generated visual direction for an entire video.

A *visual bible* is a structured JSON blueprint that describes the visual
universe, protagonist, recurring elements, and per-scene visual concepts
for a single video.  It is generated by a second LLM call that analyses
the completed script.

Phase 3 integrates the visual bible into the AI prompt pipeline so that
every generated image shares:
  - A consistent visual universe (time period, location, aesthetic).
  - A stable protagonist description (when the video features a person).
  - Recurring visual motifs (columns, smoke, coins…).
  - Metaphoric scene concepts (not literal illustrations of the narration).
  - Visual bridges between consecutive scenes.
  - Rotating shot types (establishing, detail, mood, action, symbolic).

Architecture
------------
The ``VisualBibleGenerator`` receives a completed script (list of blocks)
and a channel config, builds a specialised system prompt, and calls the
LLM.  If the primary LLM fails it falls back to the same LLM that
generated the script.
"""

from __future__ import annotations

import json
import logging
import os
import re
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Optional

logger = logging.getLogger(__name__)

_ESCENA_RE = re.compile(
    r"^ESCENA_FINAL\s+(\d+)\s*\[[^\]]*\]:\s*(.*)$", re.DOTALL,
)


def _env_float(name: str, default: float) -> float:
    try:
        return float(os.getenv(name, str(default)) or default)
    except (TypeError, ValueError):
        return default


def _env_int(name: str, default: int) -> int:
    try:
        return int(os.getenv(name, str(default)) or default)
    except (TypeError, ValueError):
        return default

# ── Fallback minimal bible when LLM completely fails ──────────────
FALLBACK_VISUAL_UNIVERSE = (
    "cinematic documentary style, atmospheric lighting, consistent color palette"
)


@dataclass
class VisualBible:
    """Parsed visual direction for a single video."""

    visual_universe: str = FALLBACK_VISUAL_UNIVERSE
    visual_tone_arc: str = "neutral→tense→hopeful"
    central_entity: dict = field(default_factory=lambda: {"type": "none"})
    recurring_elements: list[str] = field(default_factory=list)
    scene_visual_map: list[dict] = field(default_factory=list)

    @classmethod
    def _empty_scene_entry(cls, scene_idx: int) -> dict:
        """Minimal scene-map entry with an EMPTY visual_concept.

        An empty ``visual_concept`` signals the media fetcher to fall back to
        the scene's own ``search_query_en``/``texto`` (or a generic type hint)
        and append ``scene variation {i}/{N}`` for prompt uniqueness.  Reusing
        a non-empty literal here would collapse every scene to the same prompt
        → Pollinations cache returns the same image for all of them.

        Fase 3 adds the per-scene filmable-intent fields (empty by default);
        ``from_dict`` fills them from the scene text when alignment padding
        is applied.
        """
        return {
            "scene": scene_idx,
            "shot_type": "mood",
            "visual_concept": "",
            "mood": "neutral",
            "has_protagonist": False,
            "bridge_from_prev": None,
            "visual_density": "balanced",
            # ── Fase 3: filmable intent (empty → derived from scene text) ──
            "subject": "",
            "action": "",
            "object": "",
            "setting": "",
            "must_show": [],
            "must_avoid": [],
            "depiction_mode": "",
        }

    @staticmethod
    def _derive_intent(scene_text_item: Any) -> dict:
        """Best-effort intent derived from a scene text/range (fail-open)."""
        if scene_text_item is None:
            return {}
        try:
            from pipeline.scene_context import derive_scene_intent

            intent = derive_scene_intent(scene_text_item)
        except Exception:
            return {}
        if not isinstance(intent, dict):
            return {}
        return {k: v for k, v in intent.items() if v}

    @classmethod
    def from_dict(
        cls,
        data: dict,
        num_scenes: int = 0,
        scene_texts: list | None = None,
    ) -> "VisualBible":
        """Parse a raw LLM JSON dict into a ``VisualBible``, with fallbacks.

        If the LLM returned fewer ``scene_visual_map`` entries than
        ``num_scenes`` (observed: 11-32 entries for 100-146 scene videos),
        the missing entries are padded with ``_empty_scene_entry`` so the
        fetcher never runs out of per-scene concepts — the empty entries fall
        back to the scene query with a unique ``scene variation`` suffix.

        Fase 3 strict alignment: when ``scene_texts`` is provided (the final
        scene ranges, one per scene, as ``str`` or ``dict``), each padded
        entry derives its filmable intent (subject/action/must_show/
        depiction_mode) from its own scene text so the scene is never left
        without direction.  ``visual_concept`` stays empty on purpose (prompt
        uniqueness is delegated to the fetcher).
        """
        if not isinstance(data, dict):
            logger.warning("Visual bible LLM returned non-dict; using fallback")
            return cls._fallback(num_scenes)

        scene_map = list(data.get("scene_visual_map") or [])
        if num_scenes > 0 and len(scene_map) < num_scenes:
            missing = num_scenes - len(scene_map)
            logger.warning(
                "Visual bible returned %d/%d scene entries — padding %d with empty concepts",
                len(scene_map), num_scenes, missing,
            )
            texts = list(scene_texts or [])
            derived_count = 0
            for i in range(len(scene_map), num_scenes):
                entry = cls._empty_scene_entry(i)
                text_item = texts[i] if i < len(texts) else None
                intent = cls._derive_intent(text_item)
                if intent:
                    entry.update(intent)
                    derived_count += 1
                scene_map.append(entry)
            logger.warning(
                "Visual bible alignment: padded %d entries; derived intent from "
                "scene text for %d/%d (visual_concept left empty by design)",
                missing, derived_count, len(texts),
            )

        # Normalise every entry so the Fase 3 intent keys always exist
        # (LLM-provided values win; missing keys become empty defaults).
        scene_map = [
            {**cls._empty_scene_entry(i), **(e if isinstance(e, dict) else {})}
            for i, e in enumerate(scene_map)
        ]

        return cls(
            visual_universe=data.get("visual_universe") or FALLBACK_VISUAL_UNIVERSE,
            visual_tone_arc=data.get("visual_tone_arc") or "neutral→tense→hopeful",
            central_entity=data.get("central_entity") or {"type": "none"},
            recurring_elements=data.get("recurring_elements") or [],
            scene_visual_map=scene_map,
        )

    @classmethod
    def _fallback(cls, num_scenes: int) -> "VisualBible":
        """Return a minimal bible with an empty-concepts scene map.

        Every entry uses an empty ``visual_concept`` so prompt uniqueness is
        delegated to the media fetcher's ``scene variation {i}/{N}`` suffix
        (identical concepts here would all hash to the same cached image).
        """
        scene_map: list[dict] = [cls._empty_scene_entry(i) for i in range(num_scenes)]
        return cls(scene_visual_map=scene_map)

    def to_dict(self) -> dict:
        return {
            "visual_universe": self.visual_universe,
            "visual_tone_arc": self.visual_tone_arc,
            "central_entity": self.central_entity,
            "recurring_elements": self.recurring_elements,
            "scene_visual_map": self.scene_visual_map,
        }

    def with_filled_concepts(self, entries: list[dict]) -> "VisualBible":
        """Return a new bible with freshly generated scene entries merged in.

        Each entry in *entries* is keyed by its ``scene`` index; entries
        without a valid index (or out of range) are ignored.  The merge
        preserves the original bible's universe/tone/entity/elements and
        only replaces the per-scene fields of the recovered scenes.
        """
        by_scene: dict[int, dict] = {}
        for entry in entries:
            try:
                sidx = int(entry.get("scene", -1))
            except (TypeError, ValueError):
                sidx = -1
            if sidx >= 0:
                by_scene[sidx] = entry

        merged = [dict(e) for e in self.scene_visual_map]
        for sidx, entry in by_scene.items():
            if 0 <= sidx < len(merged):
                merged[sidx] = {**merged[sidx], **entry}

        return VisualBible(
            visual_universe=self.visual_universe,
            visual_tone_arc=self.visual_tone_arc,
            central_entity=self.central_entity,
            recurring_elements=self.recurring_elements,
            scene_visual_map=merged,
        )


class VisualBibleGenerator:
    """Generate a visual bible by calling the LLM with the completed script.

    Parameters
    ----------
    script_generator:
        The existing ``ScriptGenerator`` instance that owns the LLM client
        pool, JSON parsing, and channel config.  We reuse its
        ``_llm_json_call`` method rather than creating a new client.
    channel_cfg:
        Channel config object (used to build the system prompt).
    """

    def __init__(
        self,
        script_generator: Any,
        channel_cfg: Any,
    ) -> None:
        self._script_gen = script_generator
        self._channel_cfg = channel_cfg
        self.last_stats: dict[str, Any] = {}

    def generate(
        self,
        script_text: str,
        num_scenes: int,
        model_name: str | None = None,
        scene_texts: list | None = None,
    ) -> VisualBible:
        """Generate the visual bible for a script.

        Parameters
        ----------
        script_text:
            Full script text (or concatenated block texts) to analyse.
        num_scenes:
            Number of enforceable scenes in the video (used for the
            fallback when the LLM fails).
        model_name:
            Optional model override.  If ``None``, the script generator's
            default model is used.
        scene_texts:
            Optional list (one per scene) of ``str`` or scene dicts.  Used by
            Fase 3 strict alignment to derive filmable intent for the entries
            the LLM omitted.  Fail-open: ``None`` keeps the legacy behavior.

        Returns
        -------
        VisualBible
            The parsed visual bible, or a minimal fallback on failure.
        """
        from prompts.base_prompts import build_visual_bible_prompt

        system_prompt = build_visual_bible_prompt(self._channel_cfg, num_scenes)
        user_prompt = (
            "Genera la biblia visual para el siguiente guion. "
            "Responde SOLO con el JSON, sin markdown ni explicaciones.\n\n"
            f"GUION:\n---\n{script_text}\n---"
        )

        started = time.time()
        stats: dict[str, Any] = {
            "requested_entries": int(num_scenes),
            "primary_model_entries": 0,
            "recovered_or_repaired_entries": 0,
            "fallback_model_entries": 0,
            "padded_entries": 0,
            "failed_batches": 0,
            "batches": 0,
            "model_usage": {},
            "repaired_payloads": 0,
            "approx_prompt_tokens": 0,
            "approx_completion_tokens": 0,
            "latency_s": 0.0,
        }
        try:
            logger.info("Generating visual bible for %d scenes...", num_scenes)
            result = None
            last_error = None
            # Reuse the script generator's model pool with proper failover.
            # ``iter_models()`` yields ``(ModelEntry, OpenAI client)`` tuples;
            # pass the client explicitly so we never fall back to the legacy
            # client, and pass the actual model id so the call resolves
            # against the client's own provider.
            for entry, client in self._script_gen.model_pool.iter_models():
                # If a specific model was requested, skip non-matching entries.
                if model_name and model_name not in (entry.model_id, entry.display_name):
                    continue
                try:
                    result = self._script_gen._llm_json_call(
                        thinking=True,
                        client=client,
                        model=entry.model_id,
                        model_name=entry.display_name,
                        messages=[
                            {"role": "system", "content": system_prompt},
                            {"role": "user", "content": user_prompt},
                        ],
                        temperature=0.7,
                        max_tokens=_env_int("VISUAL_BIBLE_MAX_TOKENS", 4096),
                        timeout=_env_float("VISUAL_BIBLE_TIMEOUT_S", 180.0),
                        retries=1,
                    )
                    stats["model_usage"][entry.display_name] = (
                        stats["model_usage"].get(entry.display_name, 0) + 1
                    )
                    break
                except Exception as exc:
                    last_error = exc
                    logger.warning(
                        "Visual bible: model %s failed: %s",
                        entry.display_name, exc,
                    )

            if result is None:
                raise last_error if last_error else RuntimeError(
                    "No model available in pool for visual bible"
                )
            primary_map = result.get("scene_visual_map") if isinstance(result, dict) else None
            if isinstance(primary_map, list):
                stats["primary_model_entries"] = sum(
                    1 for entry in primary_map
                    if isinstance(entry, dict)
                    and str(entry.get("visual_concept") or "").strip()
                )
            stats["approx_prompt_tokens"] += max(0, len(user_prompt) // 4)
            stats["approx_completion_tokens"] += max(
                0, len(json.dumps(result, ensure_ascii=False)) // 4,
            )
            bible = VisualBible.from_dict(result, num_scenes, scene_texts=scene_texts)
        except Exception as exc:
            logger.warning(
                "Visual bible LLM call failed: %s — using fallback", exc,
            )
            bible = VisualBible._fallback(num_scenes)

        # ── Gap fill: regenerate missing/empty scene concepts ──────────
        # A partial or empty bible leaves scenes without a visual_concept;
        # those scenes then collapse to generic prompts → Pollinations
        # returns the same cached image for all of them → render-time
        # dedup rejects the duplicates → placeholder cascade → assembly
        # abort.  Try ONE targeted regeneration of the missing concepts
        # before degrading to empty entries (which the media fetcher pads).
        missing = [
            i for i, e in enumerate(bible.scene_visual_map)
            if not (e.get("visual_concept") or "").strip()
        ]
        if missing and len(missing) >= max(3, int(num_scenes * 0.05)):
            logger.info(
                "Visual bible: %d/%d scenes lack concepts — regenerating...",
                len(missing), num_scenes,
            )
            filled, gap_stats = self._generate_missing_concepts(
                script_text, missing, num_scenes, model_name,
            )
            stats["recovered_or_repaired_entries"] = len(filled)
            stats["fallback_model_entries"] = int(
                gap_stats.get("entries", 0) or 0
            )
            stats["failed_batches"] += int(gap_stats.get("failed_batches", 0) or 0)
            stats["batches"] += int(gap_stats.get("batches", 0) or 0)
            stats["approx_prompt_tokens"] += int(
                gap_stats.get("approx_prompt_tokens", 0) or 0
            )
            stats["approx_completion_tokens"] += int(
                gap_stats.get("approx_completion_tokens", 0) or 0
            )
            for model, count in (gap_stats.get("model_usage") or {}).items():
                stats["model_usage"][model] = (
                    stats["model_usage"].get(model, 0) + int(count or 0)
                )
            if filled:
                bible = bible.with_filled_concepts(filled)
                still_missing = [
                    i for i, e in enumerate(bible.scene_visual_map)
                    if not (e.get("visual_concept") or "").strip()
                ]
                logger.info(
                    "Visual bible gap fill: recovered %d/%d concepts, "
                    "%d still empty (will use scene queries)",
                    len(filled) - len(still_missing),
                    len(missing), len(still_missing),
                )

        still_empty = sum(
            1 for entry in bible.scene_visual_map
            if not str(entry.get("visual_concept") or "").strip()
        )
        stats["padded_entries"] = max(
            0,
            int(num_scenes)
            - int(stats["primary_model_entries"])
            - int(stats["recovered_or_repaired_entries"]),
        )
        stats["still_empty_entries"] = still_empty
        stats["latency_s"] = round(time.time() - started, 3)
        self.last_stats = stats
        logger.info(
            "Visual bible generated: universe=%s..., entity=%s, %d scenes; "
            "coverage primary=%d recovered=%d padded=%d failed_batches=%d "
            "latency=%.1fs",
            bible.visual_universe[:60],
            bible.central_entity.get("type", "none"),
            len(bible.scene_visual_map),
            stats["primary_model_entries"],
            stats["recovered_or_repaired_entries"],
            stats["padded_entries"],
            stats["failed_batches"],
            stats["latency_s"],
        )
        logger.info("Visual bible stats: %s", json.dumps(stats, ensure_ascii=False))
        return bible

    @staticmethod
    def _batch_script_context(script_text: str, batch: list[int]) -> str:
        """Use only the requested scene lines when the caller provides markers.

        The canary script text is formatted as ``ESCENA_FINAL <i> [a-bs]: ...``.
        Sending all 127 scenes with every retry batch is both slow and prone to
        provider timeouts.  When the markers are present, send the requested
        scenes plus a one-line instruction; otherwise keep the original text.
        """
        wanted = set(int(i) for i in batch)
        selected: list[str] = []
        matched = 0
        for line in str(script_text or "").splitlines():
            match = _ESCENA_RE.match(line.strip())
            if not match:
                continue
            matched += 1
            try:
                idx = int(match.group(1))
            except (TypeError, ValueError):
                continue
            if idx in wanted:
                selected.append(line.strip())
        if matched == 0 or not selected:
            return script_text
        header = (
            "Fragmentos del guion para las escenas solicitadas "
            f"({len(selected)} de {len(wanted)} encontradas):"
        )
        return header + "\n" + "\n".join(selected)

    def _gapfill_call(
        self,
        *,
        batch: list[int],
        script_text: str,
        num_scenes: int,
        system_prompt: str,
        model_name: str | None,
    ) -> tuple[dict | None, str]:
        """One bounded gap-fill request, with model-pool failover."""
        context = self._batch_script_context(script_text, batch)
        missing_list = ", ".join(str(i) for i in batch)
        user_prompt = (
            f"Faltan los conceptos visuales de las escenas con indices: "
            f"[{missing_list}] (de un total de {num_scenes} escenas).\n"
            "Genera UNA entrada por escena faltante, cada una con su indice exacto.\n\n"
            f"GUION:\n---\n{context}\n---"
        )
        max_tokens = min(
            4096,
            max(512, 192 + 128 * len(batch)),
        )
        max_tokens = min(max_tokens, _env_int("VISUAL_BIBLE_GAPFILL_MAX_TOKENS", 4096))
        for entry, client in self._script_gen.model_pool.iter_models():
            if model_name and model_name not in (entry.model_id, entry.display_name):
                continue
            try:
                result = self._script_gen._llm_json_call(
                    thinking=True,
                    client=client,
                    model=entry.model_id,
                    model_name=entry.display_name,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    temperature=0.7,
                    max_tokens=max_tokens,
                    timeout=_env_float("VISUAL_BIBLE_GAPFILL_TIMEOUT_S", 90.0),
                    retries=1,
                )
                if isinstance(result, dict):
                    return result, entry.display_name
            except Exception as exc:
                logger.warning(
                    "Visual bible gap fill: model %s failed (batch %s): %s",
                    entry.display_name, batch, exc,
                )
        return None, ""

    def _generate_missing_concepts(
        self,
        script_text: str,
        missing_indices: list[int],
        num_scenes: int,
        model_name: str | None = None,
    ) -> tuple[list[dict], dict[str, Any]]:
        """Targeted, batched and adaptively split recovery of missing concepts.

        A batch that fails is split into smaller halves and retried (down to a
        single scene), while later batches continue independently.  Valid
        entries from a partially successful batch are kept.  This prevents one
        malformed/timeout response from collapsing the remaining scenes to
        padding, as happened in the expanded canary (11/127 real entries).
        """
        system_prompt = (
            "Eres un director de fotografia y diseno visual experto en documentales.\n"
            "Una biblia visual previa omitio los conceptos visuales de algunas escenas.\n"
            "Tu tarea: generar SOLO los conceptos faltantes, manteniendo coherencia\n"
            "con el universo visual del guion.\n\n"
            "REGLA: METAFORA VISUAL, NO LITERAL. No describas la narracion al pie\n"
            "de la letra; crea una imagen que transmita la misma emocion. visual_concept\n"
            "debe estar en INGLES. JAMAS muestres texto en la imagen.\n\n"
            "FORMATO: Responde EXCLUSIVAMENTE con un JSON valido, sin markdown:\n"
            '{"scene_visual_map": [{"scene": <indice>, "shot_type": "mood|detail|establishing|action|symbolic", '
            '"visual_concept": "<concepto en ingles>", "mood": "<emocion>", '
            '"has_protagonist": false, "bridge_from_prev": null, '
            '"visual_density": "simple|balanced|rich"}]}'
        )

        chunk = max(1, _env_int("VISUAL_BIBLE_GAPFILL_CHUNK", 12))
        requested = {int(i) for i in missing_indices}
        pending: list[list[int]] = [
            list(missing_indices[start:start + chunk])
            for start in range(0, len(missing_indices), chunk)
        ]
        max_calls = max(
            4,
            2 * (len(pending) or 1) + 4,
        )
        max_calls = max(max_calls, _env_int("VISUAL_BIBLE_GAPFILL_MAX_CALLS", 32))

        stats: dict[str, Any] = {
            "batches": 0,
            "failed_batches": 0,
            "entries": 0,
            "model_usage": {},
            "approx_prompt_tokens": 0,
            "approx_completion_tokens": 0,
        }
        collected: dict[int, dict] = {}
        attempts: dict[tuple[int, ...], int] = {}
        calls = 0

        while pending and calls < max_calls:
            batch = pending.pop(0)
            batch = [i for i in batch if i in requested and i not in collected]
            if not batch:
                continue
            key = tuple(batch)
            attempts[key] = attempts.get(key, 0) + 1
            if attempts[key] > 2:
                stats["failed_batches"] += 1
                continue
            result, used_model = self._gapfill_call(
                batch=batch,
                script_text=script_text,
                num_scenes=num_scenes,
                system_prompt=system_prompt,
                model_name=model_name,
            )
            calls += 1
            stats["batches"] += 1
            stats["approx_prompt_tokens"] += max(
                0, (len(script_text) if len(batch) > 1 else len(script_text)) // 4,
            )
            if result is None:
                stats["failed_batches"] += 1
                if len(batch) > 1:
                    mid = len(batch) // 2
                    pending.extend([batch[:mid], batch[mid:]])
                continue

            entries = result.get("scene_visual_map") or []
            returned: set[int] = set()
            if isinstance(entries, list):
                for entry in entries:
                    if not isinstance(entry, dict):
                        continue
                    try:
                        idx = int(entry.get("scene", -1))
                    except (TypeError, ValueError):
                        continue
                    if idx not in batch or not (entry.get("visual_concept") or "").strip():
                        continue
                    collected[idx] = entry
                    returned.add(idx)
            if returned:
                stats["entries"] += len(returned)
                stats["model_usage"][used_model or "unknown"] = (
                    stats["model_usage"].get(used_model or "unknown", 0) + len(returned)
                )
                stats["approx_completion_tokens"] += max(
                    0, len(json.dumps(
                        [entry for idx, entry in collected.items() if idx in returned],
                        ensure_ascii=False,
                    )) // 4,
                )
            missing = [i for i in batch if i not in collected]
            if missing:
                if len(missing) > 1:
                    mid = len(missing) // 2
                    pending.extend([missing[:mid], missing[mid:]])
                else:
                    # One more attempt for a single scene, bounded by attempts.
                    pending.append(missing)
                if not returned:
                    stats["failed_batches"] += 1

        if collected:
            return list(collected.values()), stats
        logger.warning(
            "Visual bible gap fill failed — %d scenes stay without concepts",
            len(missing_indices),
        )
        return [], stats
